"use strict";
const { app, BrowserWindow } = require("electron");
const path = require("path");
const fs = require("fs");
const assert = require("assert/strict");
const project = path.resolve(__dirname, "..");
const asarRoot = path.join(project, "dist-requirement-preview-2.3.0.1/win-unpacked/resources/app.asar");
const config = JSON.parse(fs.readFileSync(path.join(asarRoot, "electron/update-config.json"), "utf8"));
const flavor = JSON.parse(fs.readFileSync(path.join(asarRoot, "electron/build-flavor.json"), "utf8"));
// A packaging smoke check must not read or modify the tester's signed-in profile.
const testAppData = fs.mkdtempSync(path.join(project, "build/packaged-workspace-profile-"));
app.setPath("appData", testAppData);
assert.equal(config.channel, "v11-preview");
assert.equal(config.isolatedPreview, true);
assert.equal(flavor.baseUrl, config.baseUrl);
require(path.join(asarRoot, "electron/main.js"));
app.whenReady().then(async () => {
  const wait = ms => new Promise(r => setTimeout(r, ms));
  await wait(1200);
  const win = BrowserWindow.getAllWindows()[0];
  assert(win, "packaged renderer window");
  if (win.webContents.isLoading()) await new Promise(resolve => win.webContents.once("did-finish-load", resolve));
  const result = await win.webContents.executeJavaScript(`(async()=>({flavor:await window.desktopBridge.getBuildFlavor(),navVisible:!document.getElementById('requirementNav').hidden,title:document.querySelector('.titlebar-name').innerText,request:await window.desktopBridge.requirementRequest({route:'current',method:'GET'})}))()`);
  assert.equal(result.flavor.test, true); assert(result.navVisible); assert(result.title.includes("测试版"));
  assert(app.getPath("userData").endsWith("xianma-ai-studio-preview"));
  assert.equal(result.request.code, "LOGIN_REQUIRED");
  assert(!result.request.data);
  const catalog = await win.webContents.executeJavaScript("window.desktopBridge.getAiRuntimeConfig()");
  assert(catalog.models.some(item => item.value === "deepseek-v4-pro"));
  assert(catalog.models.some(item => item.value === "gemini-3.6-flash"));
  const removedModels = ["gpt-5.5", "gpt-5.4", "gpt-5.4-mini", "gpt-5.3-codex-spark", "gpt-5.2"];
  assert.equal(catalog.models.length, 16);
  assert(!catalog.models.some(item => removedModels.includes(item.value)));
  assert(fs.existsSync(path.join(asarRoot, "renderer/workspace-modules.css")));
  fs.mkdirSync(path.join(project, "build/requirement-ui"), { recursive: true });
  fs.writeFileSync(path.join(project, "build/requirement-ui/package-login.png"), (await win.webContents.capturePage()).toPNG());
  fs.writeFileSync(path.join(project, "build/requirement-package-test.json"), JSON.stringify({ ok: true, baseUrl: config.baseUrl, channel: config.channel, isolatedPreview: config.isolatedPreview, userData: app.getPath("userData"), ...result }, null, 2));
  console.log(JSON.stringify({ ok: true, testFlavor: result.flavor.test, navVisible: result.navVisible, requestCode: result.request.code, modelCount: catalog.models.length, removedModelsHidden: true }));
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
